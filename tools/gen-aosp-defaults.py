"""Write atl_doctor/data/aosp-defaults.tsv: methods that are trivial in AOSP (empty body, `return false;`,
`return this;`, `return <parameter>;` ...), only their class, name, parameter count, kind and returned value.
No AOSP code is copied.  Only classes that ATL has its own version of (--atl-src) are listed.

    tools/gen-aosp-defaults.py --aosp ~/aosp/frameworks/base --atl-src ~/atl [-o FILE]
"""
import argparse
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
from atl_doctor.sources.aosp import DEFAULTS_FILE, open_aosp, trivial_defaults  # noqa: E402


def atl_classes(atl_src: Path) -> set[str]:
    root = atl_src / "src" if (atl_src / "src").is_dir() else atl_src
    out = set()
    for sub in ("api-impl", "ghax", "gstub"):
        for f in (root / sub).rglob("*.java"):
            out.add(".".join(f.relative_to(root / sub).with_suffix("").parts))
    return out


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--aosp", required=True, type=Path)
    ap.add_argument("--atl-src", required=True, type=Path)
    ap.add_argument("-o", "--output", type=Path, default=DEFAULTS_FILE)
    a = ap.parse_args()
    tree = open_aosp(a.aosp)
    rows = trivial_defaults(tree, atl_classes(a.atl_src))
    with open(a.output, "w", encoding="utf-8") as f:
        f.write(f"# Trivial AOSP methods (platform SDK {tree.sdk}): signature and pattern only, no AOSP code.\n")
        f.write("# Generated by tools/gen-aosp-defaults.py; do not edit.\n")
        f.write("kind\tclass\tmethod\tnparams\tvalue\n")
        for (c, m, n), (k, v) in rows.items():
            f.write(f"{k}\t{c}\t{m}\t{n}\t{v}\n")
    print(f"{len(rows)} methods -> {a.output}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
